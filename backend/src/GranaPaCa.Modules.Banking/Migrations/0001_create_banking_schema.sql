CREATE SCHEMA banking;

CREATE FUNCTION banking.enforce_append_only() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    IF current_setting('granapaca.purge', true) = 'on' THEN
        IF TG_OP = 'DELETE' THEN
            RETURN OLD;
        END IF;
        RETURN NEW;
    END IF;
    RAISE EXCEPTION 'Table %.% is append-only (ADR-012)', TG_TABLE_SCHEMA, TG_TABLE_NAME;
END;
$$;

CREATE FUNCTION banking.fold_text(input text) RETURNS text LANGUAGE sql IMMUTABLE STRICT AS $$
    SELECT translate(
        lower(input),
        'áàâãäåéèêëíìîïóòôõöúùûüçñýÿ',
        'aaaaaaeeeeiiiiooooouuuucnyy'
    );
$$;

CREATE TABLE banking.connection (
    id                   uuid PRIMARY KEY, -- UUIDv7, generated by the application (ADR-017)
    household_id         uuid NOT NULL,
    provider             text NOT NULL CHECK (provider IN ('pluggy', 'synthetic', 'file')),
    external_item_id     text NOT NULL,
    institution_name     text NOT NULL,
    brand_color          text NOT NULL DEFAULT '#A0521A',
    status               text NOT NULL CHECK (status IN ('up_to_date', 'delayed', 'error', 'expired')),
    consent_expires_at   timestamptz,
    last_synced_at       timestamptz,
    last_error_code      text,
    consecutive_failures int NOT NULL DEFAULT 0,
    first_failure_at     timestamptz,
    created_at           timestamptz NOT NULL DEFAULT now(),
    UNIQUE (household_id, provider, external_item_id)
);

CREATE TABLE banking.account (
    id                    uuid PRIMARY KEY,
    household_id          uuid NOT NULL,
    connection_id         uuid NOT NULL REFERENCES banking.connection(id) ON DELETE CASCADE,
    external_account_id   text NOT NULL,
    name                  text NOT NULL,
    kind                  text NOT NULL CHECK (kind IN ('checking', 'savings', 'credit_card')),
    last_four_digits      text,
    currency              text NOT NULL DEFAULT 'BRL' CHECK (currency = 'BRL'),
    opening_balance_cents bigint NOT NULL DEFAULT 0,
    created_at            timestamptz NOT NULL DEFAULT now(),
    UNIQUE (connection_id, external_account_id)
);

CREATE TABLE banking.balance_snapshot (
    id            uuid PRIMARY KEY,
    account_id    uuid NOT NULL REFERENCES banking.account(id) ON DELETE CASCADE,
    balance_cents bigint NOT NULL,
    captured_at   timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE banking.card_bill (
    id               uuid PRIMARY KEY,
    account_id       uuid NOT NULL REFERENCES banking.account(id) ON DELETE CASCADE,
    external_bill_id text NOT NULL,
    period_month     date NOT NULL,
    closing_on       date NOT NULL,
    due_on           date NOT NULL,
    total_cents      bigint NOT NULL,
    is_open          boolean NOT NULL DEFAULT false,
    raw_payload_enc  bytea,
    updated_at       timestamptz NOT NULL DEFAULT now(),
    UNIQUE (account_id, external_bill_id)
);

CREATE TABLE banking.transaction (
    id           uuid PRIMARY KEY,
    household_id uuid NOT NULL,
    account_id   uuid NOT NULL REFERENCES banking.account(id) ON DELETE CASCADE,
    created_at   timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE banking.transaction_source (
    id             uuid PRIMARY KEY,
    transaction_id uuid NOT NULL REFERENCES banking.transaction(id) ON DELETE CASCADE,
    account_id     uuid NOT NULL REFERENCES banking.account(id) ON DELETE CASCADE,
    source         text NOT NULL,
    external_id    text NOT NULL,
    linked_at      timestamptz NOT NULL DEFAULT now(),
    UNIQUE (account_id, source, external_id)
);

CREATE TABLE banking.transaction_version (
    id                 uuid PRIMARY KEY,
    transaction_id     uuid NOT NULL REFERENCES banking.transaction(id) ON DELETE CASCADE,
    version_number     int NOT NULL,
    content_hash       text NOT NULL,
    occurred_on        date NOT NULL,
    purchase_on        date,
    description        text NOT NULL,
    merchant_cnpj      text,
    amount_cents       bigint NOT NULL,
    currency           text NOT NULL DEFAULT 'BRL' CHECK (currency = 'BRL'),
    status             text NOT NULL DEFAULT 'posted' CHECK (status IN ('pending', 'posted')),
    bill_id            uuid REFERENCES banking.card_bill(id),
    installment_number int,
    installment_total  int,
    is_removed         boolean NOT NULL DEFAULT false,
    raw_payload_enc    bytea,
    ingested_at        timestamptz NOT NULL DEFAULT now(),
    UNIQUE (transaction_id, version_number)
);

CREATE TRIGGER trg_transaction_version_append_only
    BEFORE UPDATE OR DELETE ON banking.transaction_version
    FOR EACH ROW EXECUTE FUNCTION banking.enforce_append_only();

CREATE TABLE banking.adjustment (
    id             uuid PRIMARY KEY,
    transaction_id uuid NOT NULL REFERENCES banking.transaction(id) ON DELETE CASCADE,
    field_name     text NOT NULL CHECK (field_name IN ('category', 'essentiality', 'brand', 'kind', 'description')),
    old_value      text,
    new_value      text,
    reason         text,
    undoes_id      uuid REFERENCES banking.adjustment(id),
    created_at     timestamptz NOT NULL DEFAULT now()
);

CREATE TRIGGER trg_adjustment_append_only
    BEFORE UPDATE OR DELETE ON banking.adjustment
    FOR EACH ROW EXECUTE FUNCTION banking.enforce_append_only();

CREATE TABLE banking.transfer_link (
    id                     uuid PRIMARY KEY,
    household_id           uuid NOT NULL,
    outflow_transaction_id uuid NOT NULL REFERENCES banking.transaction(id) ON DELETE CASCADE,
    inflow_transaction_id  uuid NOT NULL REFERENCES banking.transaction(id) ON DELETE CASCADE,
    is_active              boolean NOT NULL DEFAULT true,
    linked_at              timestamptz NOT NULL DEFAULT now(),
    CHECK (outflow_transaction_id <> inflow_transaction_id)
);

CREATE UNIQUE INDEX ux_transfer_link_active_outflow
    ON banking.transfer_link (outflow_transaction_id)
    WHERE is_active;

CREATE UNIQUE INDEX ux_transfer_link_active_inflow
    ON banking.transfer_link (inflow_transaction_id)
    WHERE is_active;

CREATE TABLE banking.classification (
    transaction_id     uuid PRIMARY KEY REFERENCES banking.transaction(id) ON DELETE CASCADE,
    tx_kind            text NOT NULL CHECK (tx_kind IN ('expense', 'income', 'own_transfer', 'card_payment', 'refund', 'withdrawal', 'investment', 'redemption')),
    category           text,
    essentiality       text CHECK (essentiality IS NULL OR essentiality IN ('essential', 'important', 'flexible')),
    brand              text,
    deciding_layer     text NOT NULL,
    deciding_rule_id   uuid,
    deciding_rule_name text,
    explanation        text NOT NULL,
    classified_at      timestamptz NOT NULL DEFAULT now()
);

