CREATE SCHEMA planning;

CREATE TABLE planning.budget (
    id                      uuid PRIMARY KEY, -- UUIDv7, generated by the application (ADR-017)
    household_id            uuid NOT NULL,
    category                text NOT NULL,
    month_limit_cents       bigint NOT NULL CHECK (month_limit_cents > 0),
    alert_threshold_percent int NOT NULL DEFAULT 80 CHECK (alert_threshold_percent BETWEEN 1 AND 100),
    is_active               boolean NOT NULL DEFAULT true,
    created_at              timestamptz NOT NULL DEFAULT now(),
    updated_at              timestamptz NOT NULL DEFAULT now(),
    UNIQUE (household_id, category)
);

CREATE INDEX ix_planning_budget_household
    ON planning.budget (household_id, is_active, category);

CREATE TABLE planning.goal (
    id            uuid PRIMARY KEY, -- UUIDv7, generated by the application (ADR-017)
    household_id  uuid NOT NULL,
    name          text NOT NULL,
    target_cents  bigint NOT NULL CHECK (target_cents > 0),
    current_cents bigint NOT NULL DEFAULT 0 CHECK (current_cents >= 0),
    target_date   date,
    is_completed  boolean NOT NULL DEFAULT false,
    created_at    timestamptz NOT NULL DEFAULT now(),
    updated_at    timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX ix_planning_goal_household
    ON planning.goal (household_id, is_completed, created_at DESC);

CREATE TABLE planning.spending_alert_rule (
    id               uuid PRIMARY KEY, -- UUIDv7, generated by the application (ADR-017)
    household_id     uuid NOT NULL,
    expression       text NOT NULL,
    category         text,
    merchant_keyword text,
    limit_cents      bigint NOT NULL CHECK (limit_cents > 0),
    is_active        boolean NOT NULL DEFAULT true,
    created_at       timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX ix_planning_spending_alert_rule_household
    ON planning.spending_alert_rule (household_id, is_active, created_at DESC);
