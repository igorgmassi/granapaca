CREATE SCHEMA receipts;

CREATE TABLE receipts.consent (
    household_id           uuid PRIMARY KEY,
    item_analysis_accepted boolean NOT NULL DEFAULT false,
    dietary_notes_accepted boolean NOT NULL DEFAULT false,
    decided_at             timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE receipts.receipt (
    id               uuid PRIMARY KEY, -- UUIDv7, generated by the application (ADR-017)
    household_id     uuid NOT NULL,
    transaction_id   uuid,
    file_name        text NOT NULL,
    content_type     text NOT NULL,
    file_size_bytes  bigint NOT NULL,
    storage_rel_path text,
    nfce_access_key  text,
    issuer_name      text,
    issued_on        date,
    total_cents      bigint,
    created_at       timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX ix_receipts_receipt_household_created
    ON receipts.receipt (household_id, created_at DESC, id DESC);

CREATE INDEX ix_receipts_receipt_household_tx
    ON receipts.receipt (household_id, transaction_id)
    WHERE transaction_id IS NOT NULL;

CREATE TABLE receipts.receipt_item (
    id                 uuid PRIMARY KEY, -- UUIDv7, generated by the application (ADR-017)
    receipt_id         uuid NOT NULL REFERENCES receipts.receipt(id) ON DELETE CASCADE,
    item_index         int NOT NULL,
    description        text NOT NULL,
    quantity           numeric(12,3) NOT NULL DEFAULT 1,
    unit_price_cents   bigint NOT NULL,
    total_cents        bigint NOT NULL,
    suggested_category text,
    UNIQUE (receipt_id, item_index)
);

CREATE INDEX ix_receipts_item_receipt
    ON receipts.receipt_item (receipt_id, item_index);
