CREATE SCHEMA alerts;

CREATE TABLE alerts.alert (
    id            uuid PRIMARY KEY, -- UUIDv7, generated by the application (ADR-017)
    household_id  uuid NOT NULL,
    dedup_key     text NOT NULL,
    kind          text NOT NULL,
    severity      text NOT NULL CHECK (severity IN ('info', 'warning', 'error')),
    title         text NOT NULL,
    message       text NOT NULL,
    action_target text,
    is_read       boolean NOT NULL DEFAULT false,
    created_at    timestamptz NOT NULL DEFAULT now(),
    read_at       timestamptz,
    resolved_at   timestamptz
);

CREATE UNIQUE INDEX ux_alert_active_dedup
    ON alerts.alert (household_id, dedup_key)
    WHERE resolved_at IS NULL;

CREATE INDEX ix_alert_household_created
    ON alerts.alert (household_id, created_at DESC, id DESC);
