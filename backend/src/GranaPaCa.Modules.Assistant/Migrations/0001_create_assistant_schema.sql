CREATE SCHEMA assistant;

CREATE TABLE assistant.provider_config (
    household_id uuid PRIMARY KEY,
    provider     text NOT NULL CHECK (provider IN ('none', 'openai', 'anthropic', 'google', 'ollama')),
    model        text NOT NULL DEFAULT '',
    base_url     text,
    api_key_enc  bytea,
    updated_at   timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE assistant.chat_message (
    id                 uuid PRIMARY KEY, -- UUIDv7, generated by the application (ADR-017)
    household_id       uuid NOT NULL,
    role               text NOT NULL CHECK (role IN ('user', 'assistant')),
    content            text NOT NULL,
    period_used        text,
    numbers_cited_json text,
    provider_used      text NOT NULL,
    created_at         timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX ix_assistant_chat_message_household_created
    ON assistant.chat_message (household_id, created_at DESC, id DESC);

CREATE TABLE assistant.categorization_suggestion (
    id                     uuid PRIMARY KEY, -- UUIDv7, generated by the application (ADR-017)
    household_id           uuid NOT NULL,
    transaction_id         uuid NOT NULL,
    merchant_normalized    text NOT NULL,
    suggested_category     text,
    suggested_essentiality text CHECK (suggested_essentiality IS NULL OR suggested_essentiality IN ('essential', 'important', 'flexible')),
    confidence             numeric(4,3) NOT NULL CHECK (confidence BETWEEN 0 AND 1),
    explanation            text NOT NULL,
    status                 text NOT NULL DEFAULT 'pending' CHECK (status IN ('pending', 'confirmed', 'rejected')),
    created_at             timestamptz NOT NULL DEFAULT now(),
    decided_at             timestamptz
);

CREATE INDEX ix_assistant_suggestion_household_status
    ON assistant.categorization_suggestion (household_id, status, created_at DESC);

CREATE UNIQUE INDEX ux_assistant_suggestion_pending_tx
    ON assistant.categorization_suggestion (household_id, transaction_id)
    WHERE status = 'pending';
