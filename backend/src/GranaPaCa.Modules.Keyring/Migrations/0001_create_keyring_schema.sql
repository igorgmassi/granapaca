CREATE SCHEMA keyring;

CREATE TABLE keyring.data_key (
    id            uuid PRIMARY KEY, -- UUIDv7, generated by the application (ADR-017)
    household_id  uuid NOT NULL,
    purpose       text NOT NULL,
    master_key_id text NOT NULL,
    wrapped_key   bytea NOT NULL,
    created_at    timestamptz NOT NULL DEFAULT now(),
    retired_at    timestamptz
);

CREATE UNIQUE INDEX ux_data_key_active
    ON keyring.data_key (household_id, purpose)
    WHERE retired_at IS NULL;

CREATE INDEX ix_data_key_household_id
    ON keyring.data_key (household_id);
