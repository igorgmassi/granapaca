CREATE SCHEMA categorization;

CREATE TABLE categorization.profile_config (
    household_id    uuid PRIMARY KEY,
    occupations     text[] NOT NULL DEFAULT '{}',
    home_traits     text[] NOT NULL DEFAULT '{}',
    transport_modes text[] NOT NULL DEFAULT '{}',
    updated_at      timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE categorization.rule (
    id                        uuid PRIMARY KEY, -- UUIDv7, generated by the application (ADR-017)
    household_id              uuid NOT NULL,
    layer                     text NOT NULL CHECK (layer IN ('user', 'profile', 'system')),
    priority                  int NOT NULL DEFAULT 100,
    name                      text NOT NULL,
    explanation               text NOT NULL,
    match_cnpj                text,
    match_merchant_normalized text,
    match_pattern             text,
    category                  text,
    essentiality              text CHECK (essentiality IS NULL OR essentiality IN ('essential', 'important', 'flexible')),
    brand                     text,
    is_active                 boolean NOT NULL DEFAULT true,
    created_at                timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX ix_rule_household_layer_active_priority
    ON categorization.rule (household_id, layer, is_active, priority, created_at);
