CREATE SCHEMA identity;

CREATE TABLE identity.household (
    id         uuid PRIMARY KEY, -- UUIDv7, generated by the application (ADR-017)
    name       text NOT NULL,
    timezone   text NOT NULL DEFAULT 'America/Sao_Paulo',
    created_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE identity.owner (
    id              uuid PRIMARY KEY,
    household_id    uuid NOT NULL REFERENCES identity.household(id) ON DELETE CASCADE,
    email           text NOT NULL UNIQUE,
    display_name    text NOT NULL,
    password_hash   text NOT NULL,
    totp_secret_enc bytea,
    totp_enabled    boolean NOT NULL DEFAULT false,
    created_at      timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX ix_owner_household_id
    ON identity.owner (household_id);

CREATE TABLE identity.recovery_code (
    id         uuid PRIMARY KEY,
    owner_id   uuid NOT NULL REFERENCES identity.owner(id) ON DELETE CASCADE,
    code_hash  text NOT NULL,
    used_at    timestamptz,
    created_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX ix_recovery_code_owner_id
    ON identity.recovery_code (owner_id);

CREATE TABLE identity.pending_totp_session (
    id          uuid PRIMARY KEY,
    owner_id    uuid NOT NULL REFERENCES identity.owner(id) ON DELETE CASCADE,
    token_hash  text NOT NULL UNIQUE,
    device_name text NOT NULL,
    expires_at  timestamptz NOT NULL,
    created_at  timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX ix_pending_totp_session_owner_id
    ON identity.pending_totp_session (owner_id);

CREATE TABLE identity.session (
    id                 uuid PRIMARY KEY,
    owner_id           uuid NOT NULL REFERENCES identity.owner(id) ON DELETE CASCADE,
    household_id       uuid NOT NULL,
    device_name        text NOT NULL,
    access_token_hash  text NOT NULL UNIQUE,
    refresh_token_hash text NOT NULL UNIQUE,
    token_family_id    uuid NOT NULL,
    expires_at         timestamptz NOT NULL,
    refresh_expires_at timestamptz NOT NULL,
    revoked_at         timestamptz,
    created_at         timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX ix_session_owner_id
    ON identity.session (owner_id);

CREATE INDEX ix_session_token_family_id
    ON identity.session (token_family_id);

CREATE TABLE identity.used_refresh_token (
    token_hash      text PRIMARY KEY,
    session_id      uuid NOT NULL REFERENCES identity.session(id) ON DELETE CASCADE,
    token_family_id uuid NOT NULL,
    used_at         timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX ix_used_refresh_token_family_id
    ON identity.used_refresh_token (token_family_id);

CREATE TABLE identity.auth_attempt (
    id           uuid PRIMARY KEY,
    client_key   text NOT NULL,
    succeeded    boolean NOT NULL,
    attempted_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX ix_auth_attempt_client_key_attempted_at
    ON identity.auth_attempt (client_key, attempted_at);
